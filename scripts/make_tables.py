"""Turn results/summary.csv into results/table.md and results/key_findings.md, and sync them into
README.md and docs/writeup.md (between the RESULTS / FINDINGS markers).

Every number in the tables and findings is computed here from results/ files; nothing is typed in
by hand. If a result is bad for the agents, the sentence says so.

Usage:
    python scripts/make_tables.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from att import config  # noqa: E402

RESULTS = config.ROOT / "results"
PLANNERS = ["baseline", "baseline_reroute", "agents"]
SCEN_ORDER = ["normal", "congestion", "link_failure"]
NICE = {"1000genome-8ch": "1000Genome 8ch", "montage-01d": "Montage 0.1°",
        "1000genome-2ch": "1000Genome 2ch", "montage-005d": "Montage 0.05°",
        "normal": "normal", "congestion": "congestion", "link_failure": "link failure"}
BLOCKS = {"SUMMARY": RESULTS / "headline.md", "RESULTS": RESULTS / "table.md",
          "FINDINGS": RESULTS / "key_findings.md"}
# The README shows a compact table; the write-up shows the full one.
README_BLOCKS = {**BLOCKS, "RESULTS": RESULTS / "table_short.md"}
DOCS = [config.ROOT / "README.md", config.ROOT / "docs" / "writeup.md"]


def load(path: Path = RESULTS / "summary.csv") -> pd.DataFrame:
    df = pd.read_csv(path)
    exp = config.load_experiment()
    # D per workflow comes from the runs' own manifests (it doesn't depend on seed or data_scale)
    D = {}
    for w in df.workflow.unique():
        rid = df[df.workflow == w].iloc[0]
        import json
        man = json.loads((RESULTS / "manifests" / f"{w}__{rid.scenario}__seed{rid.seed}__{rid.planner}.json").read_text())
        D[w] = man["metrics"]["deadline_D_s"]
    df["D"] = df.workflow.map(D)
    df["completion_D"] = df.completion_s / df.D
    df.attrs["D"] = D
    df.attrs["scale"] = {w: exp["workflows"][w]["data_scale"] for w in D}
    return df


def pm(series: pd.Series, fmt: str) -> str:
    return f"{format(series.mean(), fmt)} ± {format(series.std(ddof=1), fmt)}"


def cell(df: pd.DataFrame, w: str, s: str, p: str) -> pd.DataFrame:
    return df[(df.workflow == w) & (df.scenario == s) & (df.planner == p)].sort_values("seed")


def paired(df: pd.DataFrame, w: str, s: str, a: str, b: str) -> dict:
    """Agents-vs-other comparison on the same seeds (negative delta = `a` faster)."""
    x, y = cell(df, w, s, a).set_index("seed"), cell(df, w, s, b).set_index("seed")
    d = x.completion_s - y.completion_s
    return {"delta_s": d.mean(), "delta_D": (x.completion_D - y.completion_D).mean(),
            "wins": int((d < 0).sum()), "losses": int((d > 0).sum()), "n": len(d),
            "delta_late": (x.late - y.late).mean(), "delta_failed": (x.failed_transfers - y.failed_transfers).mean()}


def make_table(df: pd.DataFrame, abl: pd.DataFrame | None) -> str:
    wfs = list(dict.fromkeys(df.workflow))
    n_seeds = df.seed.nunique()
    L = [f"_Generated by `scripts/make_tables.py` from `results/summary.csv` ({len(df)} runs). "
         f"Each cell: mean ± standard deviation over {n_seeds} evaluation seeds. "
         "D = the workflow's deadline. The network, task placement, deadlines and scaled file sizes are SYNTHETIC._",
         "",
         "| Workflow (D, data_scale) | Scenario | Planner | Completion (s) | Completion (× D) | Late transfers | Failed transfers | Completed runs |",
         "|---|---|---|---|---|---|---|---|"]
    for w in wfs:
        for s in SCEN_ORDER:
            for p in PLANNERS:
                c = cell(df, w, s, p)
                L.append(f"| {NICE[w]} ({df.attrs['D'][w]:.1f} s, ×{df.attrs['scale'][w]}) | {NICE[s]} | {p} | "
                         f"{pm(c.completion_s, '.1f')} | {pm(c.completion_D, '.3f')} | {pm(c.late, '.1f')} | "
                         f"{pm(c.failed_transfers, '.1f')} | {int(c.completed.sum())}/{len(c)} |")
    L += ["", "**Paired comparisons** (same seed = same placement, noise and events). "
          "Δ = agents − other planner; negative Δ means the agents were faster. "
          "\"Agents faster\" counts seeds where the agents finished strictly sooner.", "",
          "| Workflow | Scenario | Agents vs. | Mean Δ completion (s) | Mean Δ (× D) | Agents faster | Mean Δ late | Mean Δ failed |",
          "|---|---|---|---|---|---|---|---|"]
    for w in wfs:
        for s in SCEN_ORDER:
            for b in ["baseline", "baseline_reroute"]:
                r = paired(df, w, s, "agents", b)
                L.append(f"| {NICE[w]} | {NICE[s]} | {b} | {r['delta_s']:+.1f} | {r['delta_D']:+.3f} | "
                         f"{r['wins']}/{r['n']} seeds | {r['delta_late']:+.1f} | {r['delta_failed']:+.1f} |")
    if abl is not None:
        both = pd.concat([df, abl])
        L += ["", "**Supplementary ablation** (not part of the 180 main runs): `agents_static` uses the agents' "
              "initial plan but never reacts to events. It separates planning up front from coordinating "
              "during events. Same seeds; nothing tuned.", "",
              "| Workflow | Scenario | agents_static (× D) | agents (× D) | late: static / agents | failed: static / agents |",
              "|---|---|---|---|---|---|"]
        for w in wfs:
            for s in SCEN_ORDER:
                st, ag = cell(both, w, s, "agents_static"), cell(both, w, s, "agents")
                L.append(f"| {NICE[w]} | {NICE[s]} | {pm(st.completion_D, '.3f')} | {pm(ag.completion_D, '.3f')} | "
                         f"{st.late.mean():.1f} / {ag.late.mean():.1f} | {st.failed_transfers.mean():.1f} / "
                         f"{ag.failed_transfers.mean():.1f} |")
    mm_path = RESULTS / "maxmin" / "summary.csv"
    if mm_path.exists():
        L += maxmin_section(df, pd.read_csv(mm_path))
    llm_path = RESULTS / "llm" / "summary.csv"
    if llm_path.exists() and len(pd.read_csv(llm_path)):
        L += llm_section(df, pd.read_csv(llm_path))
    comp_path = RESULTS / "competing" / "summary.csv"
    if comp_path.exists():
        L += competing_section(pd.read_csv(comp_path))
    return "\n".join(L) + "\n"


def llm_decision_stats() -> dict[str, int]:
    """Count LLM decisions in the recorded LLM-mode runs: total, agreed with the rule, fell back."""
    import gzip
    import json
    out = {"llm_calls": 0, "agreed_with_rule": 0, "fallbacks": 0}
    for log in sorted((RESULTS / "llm" / "logs").glob("*.jsonl.gz")):
        if not any(log.name.startswith(w) for w in ("1000genome-8ch__", "montage-01d__")):
            continue  # the dev smoke test is not part of the reported runs
        for line in gzip.open(log, "rt"):
            r = json.loads(line)["saw"].get("review")
            if not r:
                continue
            if r["status"] != "ok":
                out["fallbacks"] += 1
                continue
            out["llm_calls"] += 1
            if r.get("draft", "x") == r.get("rule_choice") or r.get("action", "x") == r.get("rule_would"):
                out["agreed_with_rule"] += 1
    return out


def llm_section(df: pd.DataFrame, llm: pd.DataFrame) -> list[str]:
    """LLM mode: the agent team with Claude making the coordinator's final call (mode=llm)."""
    import json
    llm = llm.copy()
    llm["planner"] = "agents_llm"
    llm["D"] = llm.workflow.map(df.attrs["D"])
    llm["completion_D"] = llm.completion_s / llm.D
    both = pd.concat([df, llm])
    st = llm_decision_stats()
    spend = json.loads((RESULTS / "llm" / "spend.json").read_text()) if (RESULTS / "llm" / "spend.json").exists() else {}
    L = ["", f"**Supplementary: LLM mode** (`mode=llm`, reported separately; not part of the 180 main runs). "
         f"Same {len(llm)} cells as `agents`, but Claude ({spend.get('model', 'claude')}) makes the coordinator's final "
         "decision (one call per initial plan and per event that has a proposal). "
         f"{st['llm_calls']} Claude decisions, {st['agreed_with_rule']} identical to what the rule coordinator would "
         f"have chosen, {st['fallbacks']} fallbacks to rules; API spend upper bound "
         f"${spend.get('usd_upper_bound', 0):.2f} (including a dev smoke test).", "",
         "| Workflow | Scenario | agents, rule (× D) | agents, LLM (× D) | late: rule / LLM | LLM faster than rule | LLM faster than baseline / baseline_reroute |",
         "|---|---|---|---|---|---|---|"]
    for w in dict.fromkeys(df.workflow):
        for s in SCEN_ORDER:
            if cell(both, w, s, "agents_llm").empty:
                continue
            r = paired(both, w, s, "agents_llm", "agents")
            b = [paired(both, w, s, "agents_llm", x) for x in ("baseline", "baseline_reroute")]
            L.append(f"| {NICE[w]} | {NICE[s]} | {pm(cell(both, w, s, 'agents').completion_D, '.3f')} | "
                     f"{pm(cell(both, w, s, 'agents_llm').completion_D, '.3f')} | "
                     f"{m(both, w, s, 'agents', 'late'):.1f} / {m(both, w, s, 'agents_llm', 'late'):.1f} | "
                     f"{r['wins']}/{r['n']} (slower on {r['losses']}) | {b[0]['wins']}/{b[0]['n']} / {b[1]['wins']}/{b[1]['n']} |")
    return L


def maxmin_section(df: pd.DataFrame, mm: pd.DataFrame) -> list[str]:
    """The same 180-run grid under max-min fair sharing."""
    mm = mm.copy()
    mm["D"] = mm.workflow.map(df.attrs["D"])
    mm["completion_D"] = mm.completion_s / mm.D
    L = ["", "**Supplementary: max-min fair sharing** (a robustness check outside the main results). The same "
         f"{len(mm)} runs with weighted max-min fair sharing instead of proportional sharing; nothing re-tuned. "
         "Mean completion (× D), proportional → max-min; and the agents' paired wins under max-min.", "",
         "| Workflow | Scenario | baseline | baseline_reroute | agents | Agents faster than baseline / baseline_reroute (max-min) |",
         "|---|---|---|---|---|---|"]
    for w in dict.fromkeys(df.workflow):
        for s in SCEN_ORDER:
            cells = [f"{m(df, w, s, p):.3f} → {m(mm, w, s, p):.3f}" for p in PLANNERS]
            wins = [paired(mm, w, s, "agents", b) for b in ("baseline", "baseline_reroute")]
            L.append(f"| {NICE[w]} | {NICE[s]} | " + " | ".join(cells) + " | "
                     + " / ".join(f"{r['wins']}/{r['n']}" for r in wins) + " |")
    return L


def competing_section(c: pd.DataFrame) -> list[str]:
    """Both result workflows share the normal network at once (30 runs)."""
    wfs = [k.split(":")[0] for k in c.columns if k.endswith(":completion_D")]
    L = ["", "**Supplementary: competing workflows** (not part of the 180 main runs). "
         + " and ".join(NICE[w] for w in wfs) + " start together on the `normal` network; each keeps its "
         "own data_scale and deadline D. Completion is shown as a fraction of each workflow's own D. "
         "Same evaluation seeds; nothing tuned.", "",
         "| Planner | " + " | ".join(f"{NICE[w]} completion (× its D) | {NICE[w]} late" for w in wfs)
         + " | Runs where every workflow met its D |",
         "|---|" + "---|---|" * len(wfs) + "---|"]
    for p in PLANNERS:
        r = c[c.planner == p]
        met = sum(all(row[f"{w}:completion_D"] <= 1.0 for w in wfs) for _, row in r.iterrows())
        L.append(f"| {p} | " + " | ".join(f"{pm(r[f'{w}:completion_D'], '.3f')} | {r[f'{w}:late'].mean():.1f}"
                                          for w in wfs) + f" | {met}/{len(r)} |")
    a = c[c.planner == "agents"].set_index("seed")
    for b in ("baseline", "baseline_reroute"):
        o = c[c.planner == b].set_index("seed")
        wins = " and ".join(f"{int((a[f'{w}:completion_s'] < o[f'{w}:completion_s']).sum())}/{len(a)} seeds for {NICE[w]}"
                            for w in wfs)
        L.append("")
        L.append(f"Agents vs. {b}: faster on {wins}.")
    return L


def m(df, w, s, p, col="completion_D"):
    return cell(df, w, s, p)[col].mean()


def make_findings(df: pd.DataFrame, abl: pd.DataFrame | None) -> str:
    """Plain sentences computed from the numbers. Wording follows the sign of each result."""
    G, M = "1000genome-8ch", "montage-01d"
    out = []

    # 1. link failure, and how much simple rerouting recovers
    bG, rG, aG = (m(df, G, "link_failure", p) for p in PLANNERS)
    bM, rM, aM = (m(df, M, "link_failure", p) for p in PLANNERS)
    shG = (bG - rG) / (bG - aG) if bG > aG else float("nan")
    shM = (bM - rM) / (bM - aM) if bM > aM else float("nan")
    out.append(f"When the StarLight-Caltech link fails, the baseline on {NICE[G]} takes {bG:.2f} D, and "
               f"{m(df, G, 'link_failure', 'baseline', 'failed_transfers'):.1f} transfers per run time out at least once. "
               f"Rerouting alone brings it to {rG:.2f} D and the agents to {aG:.2f} D, so rerouting covers "
               f"{shG:.0%} of the agents' gain. On {NICE[M]} the same three numbers are {bM:.2f}, {rM:.2f} and "
               f"{aM:.2f} D, and rerouting covers {shM:.0%}.")

    # 2. congestion on the workflow it stresses
    b, r, a = (m(df, G, "congestion", p) for p in PLANNERS)
    pr = paired(df, G, "congestion", "agents", "baseline_reroute")
    same = "the same" if abs(b - r) < 1e-12 else "close to the"
    out.append(f"Congestion is where coordination paid off. On {NICE[G]} the rerouting baseline ignores the surge, "
               f"so it scores {same} result as the plain baseline: {r:.2f} D with "
               f"{m(df, G, 'congestion', 'baseline_reroute', 'late'):.1f} late transfers per run. The agents move "
               f"transfers off the congested link and finish in {a:.2f} D with "
               f"{m(df, G, 'congestion', 'agents', 'late'):.1f} late, faster on {pr['wins']} of {pr['n']} seeds.")

    # 3. planning vs reacting
    gn = 1 - m(df, G, "normal", "agents") / m(df, G, "normal", "baseline")
    mn = 1 - m(df, M, "normal", "agents") / m(df, M, "normal", "baseline")
    s3 = (f"With no events at all the agents are already {gn:.0%} faster than the baseline on {NICE[G]} "
          f"({mn:.1%} on {NICE[M]}), because they spread large transfers over parallel routes from the start.")
    if abl is not None:
        both = pd.concat([df, abl])
        s3 += (f" That plan alone does not carry them through events, though. Without reactions "
               f"(agents_static) the same plan takes {m(both, G, 'congestion', 'agents_static'):.2f} D under "
               f"congestion and {m(both, G, 'link_failure', 'agents_static'):.2f} D under the link failure, against "
               f"{m(both, G, 'congestion', 'agents'):.2f} and {m(both, G, 'link_failure', 'agents'):.2f} D "
               f"when the agents react.")
    out.append(s3)

    # 4. where the agents gained little
    bn, bc = m(df, M, "normal", "baseline"), m(df, M, "congestion", "baseline")
    an, ac = m(df, M, "normal", "agents"), m(df, M, "congestion", "agents")
    pn = paired(df, M, "normal", "agents", "baseline")
    out.append(f"Congestion barely touched {NICE[M]} (baseline {bn:.3f} D in normal, {bc:.3f} D with the surge), "
               f"because Montage moves most of its data after the surge window closes. The agents' small edge there "
               f"({an:.3f} and {ac:.3f} D, {pn['delta_s']:+.1f} s per run in normal) is the planning effect again.")

    # 4b. the agents' clearest loss: the dev workflow used for tuning
    by_wf: dict[str, list[str]] = {}
    for (w, sc), (a, b) in dev_comparison().items():
        if a > b:
            by_wf.setdefault(w, []).append(f"{NICE[sc]} ({a:.3f} D against {b:.3f} D)")
    for w, cases in by_wf.items():
        out.append(f"The agents lost on the smaller {NICE[w]} workflow used for tuning, in " + " and ".join(cases) +
                   " over the tuning seeds. Their start-of-run forecast can only assume today's network, and it "
                   "sometimes chose a rebalanced plan that ran slower than plain lowest-delay routing.")

    # 5. pile-on effect + overall losses
    lr, la = m(df, M, "link_failure", "baseline_reroute", "late"), m(df, M, "link_failure", "agents", "late")
    losses = sum(paired(df, w, s, "agents", b)["losses"] for w in (G, M) for s in SCEN_ORDER
                 for b in ("baseline", "baseline_reroute"))
    total = sum(paired(df, w, s, "agents", b)["n"] for w in (G, M) for s in SCEN_ORDER
                for b in ("baseline", "baseline_reroute"))
    tail = ("they were never slower" if losses == 0 else f"they were slower in {losses}")
    out.append(f"Rerouting has its own failure mode. On {NICE[M]} it sends every stuck transfer to the same backup "
               f"route and still leaves {lr:.1f} late transfers per run, where the agents, spreading and prioritizing, "
               f"leave {la:.1f}. Across all {total} paired comparisons on the result workflows, {tail}.")
    return "\n\n".join(out) + "\n"


def dev_comparison() -> dict[tuple[str, str], tuple[float, float]]:
    """(dev workflow, scenario) -> (agents, baseline) mean completion / D on the tuning seeds,
    read from the two tuning result files (results/tuning/*.json)."""
    import json
    net = json.loads((RESULTS / "tuning" / "tuning.json").read_text())
    ag = json.loads((RESULTS / "tuning" / "agent_tuning.json").read_text())
    chosen = next(r for r in ag["rows"] if all(r[k] == v for k, v in ag["chosen"].items()))
    out = {}
    for w in ag["dev_workflows"]:
        rec = net["workflows"][w]
        base = {"normal": rec["scale_sweep"][str(rec["data_scale"])]["completion_over_D"]}
        for sc, attempts in rec["scenarios"].items():
            base[sc] = attempts[0]["completion_over_D"]  # as configured (dev scenarios were never overridden)
        for sc, b in base.items():
            out[(w, sc)] = (chosen["per_case"][f"{w}/{sc}"]["completion_D"], b)
    return out


def make_short_table(df: pd.DataFrame) -> str:
    """One row per workflow x scenario: mean completion (x D) and late transfers per planner."""
    L = ["Mean over 10 seeds: completion time as a fraction of the deadline D (late transfers per run). "
         "Full tables: [`results/table.md`](results/table.md).", "",
         "| Workflow | Scenario | baseline | baseline_reroute | agents |", "|---|---|---|---|---|"]
    for w in dict.fromkeys(df.workflow):
        for s in SCEN_ORDER:
            L.append(f"| {NICE[w]} | {NICE[s]} | " + " | ".join(
                f"{m(df, w, s, p):.2f} ({m(df, w, s, p, 'late'):.1f})" for p in PLANNERS) + " |")
    return "\n".join(L) + "\n"


def make_headline(df: pd.DataFrame) -> str:
    """The main result, for the write-up's summary and the README."""
    G, M = "1000genome-8ch", "montage-01d"
    pairs = [paired(df, w, s, "agents", b) for w in (G, M) for s in SCEN_ORDER for b in ("baseline", "baseline_reroute")]
    wins, total = sum(p["wins"] for p in pairs), sum(p["n"] for p in pairs)
    late_a = int(df[df.planner == "agents"].late.sum())
    share = {}
    for w in (G, M):
        b, r, a = (m(df, w, "link_failure", p) for p in PLANNERS)
        share[w] = (b - r) / (b - a)
    rc, ac = m(df, G, "congestion", "baseline_reroute"), m(df, G, "congestion", "agents")
    beat = (f"beat both baselines in all {total}" if wins == total else f"beat the baselines in {wins} of {total}")
    return (f"Across {len(df)} simulated runs, the agent team {beat} same-seed comparisons and had {late_a} late "
            f"transfers. Plain rerouting already fixes much of a link failure ({share[G]:.0%} of the agents' gain on "
            f"{NICE[G]}, {share[M]:.0%} on {NICE[M]}). Congestion is different: rerouting does nothing there, and on "
            f"{NICE[G]} the agents finish at {ac:.2f} D against {rc:.2f} D, where D is the deadline.\n")


def sync_docs() -> list[str]:
    """Rewrite the marked blocks in README.md and docs/writeup.md from the generated files."""
    changed = []
    for doc in DOCS:
        if not doc.exists():
            continue
        text = doc.read_text()
        new = text
        blocks = README_BLOCKS if doc.name == "README.md" else BLOCKS
        for tag, src in blocks.items():
            start, end = f"<!-- {tag}:START -->", f"<!-- {tag}:END -->"
            if start in new and end in new:
                head, rest = new.split(start, 1)
                _, tail = rest.split(end, 1)
                new = head + start + "\n" + src.read_text() + end + tail
        if new != text:
            doc.write_text(new)
            changed.append(str(doc.relative_to(config.ROOT)))
    return changed


def main() -> None:
    df = load()
    abl_path = RESULTS / "ablation" / "summary.csv"
    abl = pd.read_csv(abl_path) if abl_path.exists() else None
    if abl is not None:
        abl["D"] = abl.workflow.map(df.attrs["D"])
        abl["completion_D"] = abl.completion_s / abl.D
    (RESULTS / "table.md").write_text(make_table(df, abl))
    (RESULTS / "key_findings.md").write_text(make_findings(df, abl))
    (RESULTS / "headline.md").write_text(make_headline(df))
    (RESULTS / "table_short.md").write_text(make_short_table(df))
    print("wrote results/table.md, results/key_findings.md, results/headline.md")
    for d in sync_docs():
        print(f"updated blocks in {d}")


if __name__ == "__main__":
    main()
