"""Turn results/summary.csv into results/table.md and results/key_findings.md, and sync them into
README.md and docs/writeup.md (between the RESULTS / FINDINGS markers).

Every number in the tables and findings is computed here from results/ files; nothing is typed in
by hand. If a result is bad for the agents, the sentence says so.

Usage:
    python scripts/make_tables.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from att import config  # noqa: E402

RESULTS = config.ROOT / "results"
PLANNERS = ["baseline", "baseline_reroute", "agents"]
SCEN_ORDER = ["normal", "congestion", "link_failure"]
NICE = {"1000genome-8ch": "1000Genome 8ch", "montage-01d": "Montage 0.1°",
        "1000genome-2ch": "1000Genome 2ch", "montage-005d": "Montage 0.05°",
        "normal": "normal", "congestion": "congestion", "link_failure": "link failure"}
BLOCKS = {"SUMMARY": RESULTS / "headline.md", "RESULTS": RESULTS / "table.md",
          "FINDINGS": RESULTS / "key_findings.md"}
DOCS = [config.ROOT / "README.md", config.ROOT / "docs" / "writeup.md"]


def load(path: Path = RESULTS / "summary.csv") -> pd.DataFrame:
    df = pd.read_csv(path)
    exp = config.load_experiment()
    # D per workflow comes from the runs' own manifests (it doesn't depend on seed or data_scale)
    D = {}
    for w in df.workflow.unique():
        rid = df[df.workflow == w].iloc[0]
        import json
        man = json.loads((RESULTS / "manifests" / f"{w}__{rid.scenario}__seed{rid.seed}__{rid.planner}.json").read_text())
        D[w] = man["metrics"]["deadline_D_s"]
    df["D"] = df.workflow.map(D)
    df["completion_D"] = df.completion_s / df.D
    df.attrs["D"] = D
    df.attrs["scale"] = {w: exp["workflows"][w]["data_scale"] for w in D}
    return df


def pm(series: pd.Series, fmt: str) -> str:
    return f"{format(series.mean(), fmt)} ± {format(series.std(ddof=1), fmt)}"


def cell(df: pd.DataFrame, w: str, s: str, p: str) -> pd.DataFrame:
    return df[(df.workflow == w) & (df.scenario == s) & (df.planner == p)].sort_values("seed")


def paired(df: pd.DataFrame, w: str, s: str, a: str, b: str) -> dict:
    """Agents-vs-other comparison on the same seeds (negative delta = `a` faster)."""
    x, y = cell(df, w, s, a).set_index("seed"), cell(df, w, s, b).set_index("seed")
    d = x.completion_s - y.completion_s
    return {"delta_s": d.mean(), "delta_D": (x.completion_D - y.completion_D).mean(),
            "wins": int((d < 0).sum()), "losses": int((d > 0).sum()), "n": len(d),
            "delta_late": (x.late - y.late).mean(), "delta_failed": (x.failed_transfers - y.failed_transfers).mean()}


def make_table(df: pd.DataFrame, abl: pd.DataFrame | None) -> str:
    wfs = list(dict.fromkeys(df.workflow))
    n_seeds = df.seed.nunique()
    L = [f"_Generated by `scripts/make_tables.py` from `results/summary.csv` ({len(df)} runs). "
         f"Each cell: mean ± standard deviation over {n_seeds} evaluation seeds. "
         "D = the workflow's deadline. The network, task placement, deadlines and scaled file sizes are SYNTHETIC._",
         "",
         "| Workflow (D, data_scale) | Scenario | Planner | Completion (s) | Completion (× D) | Late transfers | Failed transfers | Completed runs |",
         "|---|---|---|---|---|---|---|---|"]
    for w in wfs:
        for s in SCEN_ORDER:
            for p in PLANNERS:
                c = cell(df, w, s, p)
                L.append(f"| {NICE[w]} ({df.attrs['D'][w]:.1f} s, ×{df.attrs['scale'][w]}) | {NICE[s]} | {p} | "
                         f"{pm(c.completion_s, '.1f')} | {pm(c.completion_D, '.3f')} | {pm(c.late, '.1f')} | "
                         f"{pm(c.failed_transfers, '.1f')} | {int(c.completed.sum())}/{len(c)} |")
    L += ["", "**Paired comparisons** (same seed = same placement, noise and events). "
          "Δ = agents − other planner; negative Δ means the agents were faster. "
          "\"Agents faster\" counts seeds where the agents finished strictly sooner.", "",
          "| Workflow | Scenario | Agents vs. | Mean Δ completion (s) | Mean Δ (× D) | Agents faster | Mean Δ late | Mean Δ failed |",
          "|---|---|---|---|---|---|---|---|"]
    for w in wfs:
        for s in SCEN_ORDER:
            for b in ["baseline", "baseline_reroute"]:
                r = paired(df, w, s, "agents", b)
                L.append(f"| {NICE[w]} | {NICE[s]} | {b} | {r['delta_s']:+.1f} | {r['delta_D']:+.3f} | "
                         f"{r['wins']}/{r['n']} seeds | {r['delta_late']:+.1f} | {r['delta_failed']:+.1f} |")
    if abl is not None:
        both = pd.concat([df, abl])
        L += ["", "**Supplementary ablation** (not part of the 180 main runs): `agents_static` uses the agents' "
              "initial plan but never reacts to events. It separates planning up front from coordinating "
              "during events. Same seeds; nothing tuned.", "",
              "| Workflow | Scenario | agents_static (× D) | agents (× D) | late: static / agents | failed: static / agents |",
              "|---|---|---|---|---|---|"]
        for w in wfs:
            for s in SCEN_ORDER:
                st, ag = cell(both, w, s, "agents_static"), cell(both, w, s, "agents")
                L.append(f"| {NICE[w]} | {NICE[s]} | {pm(st.completion_D, '.3f')} | {pm(ag.completion_D, '.3f')} | "
                         f"{st.late.mean():.1f} / {ag.late.mean():.1f} | {st.failed_transfers.mean():.1f} / "
                         f"{ag.failed_transfers.mean():.1f} |")
    return "\n".join(L) + "\n"


def m(df, w, s, p, col="completion_D"):
    return cell(df, w, s, p)[col].mean()


def make_findings(df: pd.DataFrame, abl: pd.DataFrame | None) -> str:
    """4-6 plain sentences, each computed from the numbers (wording follows the sign of each result)."""
    G, M = "1000genome-8ch", "montage-01d"
    out = []

    # 1. headline: link failure, and how much simple rerouting recovers
    parts = []
    for w in (G, M):
        b, r, a = (m(df, w, "link_failure", p) for p in PLANNERS)
        share = (b - r) / (b - a) if b > a else float("nan")
        parts.append(f"on {NICE[w]} the baseline took {b:.2f} D with {m(df, w, 'link_failure', 'baseline', 'failed_transfers'):.1f} "
                     f"failed transfers per run, simple rerouting {r:.2f} D, and the agents {a:.2f} D, so rerouting alone "
                     f"recovered {share:.0%} of the agents' improvement")
    out.append("Under the link failure, " + "; ".join(parts) + ".")

    # 2. congestion on the workflow it stresses
    b, r, a = (m(df, G, "congestion", p) for p in PLANNERS)
    pr = paired(df, G, "congestion", "agents", "baseline_reroute")
    out.append(f"Congestion is where coordination mattered most: on {NICE[G]} baseline_reroute ignores surges and was "
               f"{'identical to' if abs(b - r) < 1e-12 else 'close to'} the baseline ({r:.2f} D, "
               f"{m(df, G, 'congestion', 'baseline_reroute', 'late'):.1f} late transfers per run), while the agents, "
               f"which move transfers off the congested link, took {a:.2f} D with "
               f"{m(df, G, 'congestion', 'agents', 'late'):.1f} late and were faster on {pr['wins']}/{pr['n']} seeds.")

    # 3. planning vs reacting
    gn = 1 - m(df, G, "normal", "agents") / m(df, G, "normal", "baseline")
    mn = 1 - m(df, M, "normal", "agents") / m(df, M, "normal", "baseline")
    s3 = (f"Part of the agents' advantage is planning, not reacting: with no events at all they were already "
          f"{gn:.0%} faster than the baseline on {NICE[G]} and {mn:.1%} faster on {NICE[M]}, by spreading large "
          f"transfers over parallel routes")
    if abl is not None:
        both = pd.concat([df, abl])
        s3 += (f"; but the same initial plan without event reactions (agents_static) took "
               f"{m(both, G, 'congestion', 'agents_static'):.2f} D under congestion and "
               f"{m(both, G, 'link_failure', 'agents_static'):.2f} D under the link failure on {NICE[G]}, versus "
               f"{m(both, G, 'congestion', 'agents'):.2f} D and {m(both, G, 'link_failure', 'agents'):.2f} D "
               f"when the agents react")
    out.append(s3 + ".")

    # 4. where the agents gained little or lost (result workflows, then the dev workflows used for tuning)
    bn, bc = m(df, M, "normal", "baseline"), m(df, M, "congestion", "baseline")
    an, ac = m(df, M, "normal", "agents"), m(df, M, "congestion", "agents")
    pn = paired(df, M, "normal", "agents", "baseline")
    s4 = (f"Where there was little to fix, the agents gained little: congestion did not stress {NICE[M]} "
          f"(baseline {bn:.3f} D in normal and {bc:.3f} D under congestion, because Montage moves most of its data "
          f"after the surge window ends), and the agents' edge there ({an:.3f} D in normal, {ac:.3f} D under "
          f"congestion; {pn['delta_s']:+.1f} s per run in normal) is a small planning effect, not a response to "
          f"congestion")
    out.append(s4 + ".")

    # 4b. the agents' clearest loss: the dev workflow used for tuning
    by_wf: dict[str, list[str]] = {}
    for (w, sc), (a, b) in dev_comparison().items():
        if a > b:
            by_wf.setdefault(w, []).append(f"{NICE[sc]} ({a:.3f} D vs. {b:.3f} D)")
    for w, cases in by_wf.items():
        out.append(f"The agents did not always help: on the smaller {NICE[w]} workflow used for tuning, they were "
                   f"slower than the baseline in " + " and ".join(cases) + " (means over the tuning seeds): their "
                   f"start-of-run forecast can only assume today's network, and it sometimes picked a rebalanced "
                   f"plan that then ran slower than plain lowest-delay routing.")

    # 5. pile-on effect + overall losses
    lr, la = m(df, M, "link_failure", "baseline_reroute", "late"), m(df, M, "link_failure", "agents", "late")
    losses = sum(paired(df, w, s, "agents", b)["losses"] for w in (G, M) for s in SCEN_ORDER
                 for b in ("baseline", "baseline_reroute"))
    total = sum(paired(df, w, s, "agents", b)["n"] for w in (G, M) for s in SCEN_ORDER
                for b in ("baseline", "baseline_reroute"))
    tail = ("the agents were never slower" if losses == 0 else f"the agents were slower in {losses}")
    out.append(f"On {NICE[M]} under the link failure, simple rerouting moved every stuck transfer onto the same "
               f"backup route and still left {lr:.1f} late transfers per run, versus {la:.1f} for the agents, which "
               f"spread and prioritized them; across all {total} paired comparisons on the result workflows {tail}.")
    return "\n\n".join(out) + "\n"


def dev_comparison() -> dict[tuple[str, str], tuple[float, float]]:
    """(dev workflow, scenario) -> (agents, baseline) mean completion / D on the tuning seeds,
    read from the two tuning result files (results/tuning/*.json)."""
    import json
    net = json.loads((RESULTS / "tuning" / "tuning.json").read_text())
    ag = json.loads((RESULTS / "tuning" / "agent_tuning.json").read_text())
    chosen = next(r for r in ag["rows"] if all(r[k] == v for k, v in ag["chosen"].items()))
    out = {}
    for w in ag["dev_workflows"]:
        rec = net["workflows"][w]
        base = {"normal": rec["scale_sweep"][str(rec["data_scale"])]["completion_over_D"]}
        for sc, attempts in rec["scenarios"].items():
            base[sc] = attempts[0]["completion_over_D"]  # as configured (dev scenarios were never overridden)
        for sc, b in base.items():
            out[(w, sc)] = (chosen["per_case"][f"{w}/{sc}"]["completion_D"], b)
    return out


def make_headline(df: pd.DataFrame) -> str:
    """The main result in one sentence (used as the write-up's summary and the README's lead)."""
    G, M = "1000genome-8ch", "montage-01d"
    pairs = [paired(df, w, s, "agents", b) for w in (G, M) for s in SCEN_ORDER for b in ("baseline", "baseline_reroute")]
    wins, total = sum(p["wins"] for p in pairs), sum(p["n"] for p in pairs)
    late_a = int(df[df.planner == "agents"].late.sum())
    share = {}
    for w in (G, M):
        b, r, a = (m(df, w, "link_failure", p) for p in PLANNERS)
        share[w] = (b - r) / (b - a)
    rc, ac = m(df, G, "congestion", "baseline_reroute"), m(df, G, "congestion", "agents")
    return (f"In {len(df)} simulated runs, the agent team finished sooner than the baselines in {wins} of {total} "
            f"same-seed comparisons and had {late_a} late transfers; simple rerouting alone already recovered a large "
            f"share of the damage from a link failure ({share[G]:.0%} of the agents' improvement on {NICE[G]}, "
            f"{share[M]:.0%} on {NICE[M]}), but under congestion only the coordinated agents helped "
            f"({NICE[G]}: {rc:.2f} D with rerouting vs. {ac:.2f} D with the agents, where D is the deadline).\n")


def sync_docs() -> list[str]:
    """Rewrite the marked blocks in README.md and docs/writeup.md from the generated files."""
    changed = []
    for doc in DOCS:
        if not doc.exists():
            continue
        text = doc.read_text()
        new = text
        for tag, src in BLOCKS.items():
            start, end = f"<!-- {tag}:START -->", f"<!-- {tag}:END -->"
            if start in new and end in new:
                head, rest = new.split(start, 1)
                _, tail = rest.split(end, 1)
                new = head + start + "\n" + src.read_text() + end + tail
        if new != text:
            doc.write_text(new)
            changed.append(str(doc.relative_to(config.ROOT)))
    return changed


def main() -> None:
    df = load()
    abl_path = RESULTS / "ablation" / "summary.csv"
    abl = pd.read_csv(abl_path) if abl_path.exists() else None
    if abl is not None:
        abl["D"] = abl.workflow.map(df.attrs["D"])
        abl["completion_D"] = abl.completion_s / abl.D
    (RESULTS / "table.md").write_text(make_table(df, abl))
    (RESULTS / "key_findings.md").write_text(make_findings(df, abl))
    (RESULTS / "headline.md").write_text(make_headline(df))
    print("wrote results/table.md, results/key_findings.md, results/headline.md")
    for d in sync_docs():
        print(f"updated blocks in {d}")


if __name__ == "__main__":
    main()
